import { readFileSync, writeFileSync } from "node:fs";
const themes = JSON.parse(
  readFileSync(new URL("./themes.json", import.meta.url)),
);
const selectors = {
  paper: ":root",
  forest: "[data-theme=dark]",
  "petrol-light": "[data-palette=petrol]:not([data-theme=dark])",
  "petrol-dark": "[data-palette=petrol][data-theme=dark]",
  "indigo-light": "[data-palette=indigo]:not([data-theme=dark])",
  "indigo-dark": "[data-palette=indigo][data-theme=dark]",
  "amber-light": "[data-palette=amber]:not([data-theme=dark])",
  "amber-dark": "[data-palette=amber][data-theme=dark]",
};
let css = "/* Generated by packages/tokens/build.mjs. Edit themes.json. */\n";
for (const [name, t] of Object.entries(themes))
  css += `${selectors[name]} {\n${Object.entries(t)
    .map(([k, v]) => `  --wl-${k}: ${v};`)
    .join(
      "\n",
    )}\n  color-scheme: ${name === "forest" || name.endsWith("-dark") ? "dark" : "light"};\n}\n`;
css += `:root {--wl-space-1:4px;--wl-space-2:8px;--wl-space-3:12px;--wl-space-4:16px;--wl-space-6:24px;--wl-space-8:32px;--wl-radius-control:8px;--wl-radius-surface:16px;--wl-surface-padding:24px;--wl-gap:24px;--wl-font:Inter,system-ui,sans-serif;}
:root,[data-theme],[data-palette]{
--wl-color-surface-primary:var(--wl-surface);--wl-color-surface-secondary:var(--wl-muted);--wl-color-surface-technical:var(--wl-muted);
--wl-color-text-primary:var(--wl-text);--wl-color-text-secondary:var(--wl-secondary);--wl-color-text-inverse:var(--wl-on);
--wl-color-border-default:var(--wl-border);--wl-color-border:var(--wl-border);--wl-color-border-strong:var(--wl-accent);
--wl-color-action-primary:var(--wl-accent);--wl-color-action-hover:var(--wl-hover);--wl-color-accent:var(--wl-accent);--wl-color-focus:var(--wl-accent);
--wl-color-danger:var(--wl-danger);--wl-color-info:var(--wl-info);--wl-color-warning:var(--wl-warning);--wl-color-success:var(--wl-success);
--wl-avatar-bg:var(--wl-muted);--wl-avatar-fg:var(--wl-text);--wl-inline-action:var(--wl-accent);--wl-inline-action-hover:var(--wl-hover);
--wl-switch-off:var(--wl-off);--wl-switch-on:var(--wl-accent);--wl-surface-radius:var(--wl-radius-surface);
}
`;
writeFileSync(new URL("./semantic.css", import.meta.url), css);
const labels = {
  paper: "Papel claro",
  forest: "Floresta escura",
  "indigo-light": "Índigo claro",
  "indigo-dark": "Índigo escuro",
  "amber-light": "Âmbar claro",
  "amber-dark": "Âmbar escuro",
  "petrol-light": "Petróleo claro",
  "petrol-dark": "Petróleo escuro",
};
const options = Object.fromEntries(
  Object.entries(themes).map(([key, t]) => [
    key,
    [
      labels[key],
      t.accent,
      t.muted,
      key === "forest" || key.endsWith("-dark") ? "Escuro" : "Claro",
    ],
  ]),
);
writeFileSync(
  new URL("./themes.js", import.meta.url),
  "// Generated from themes.json\nexport const themeOptions = " +
    JSON.stringify(options, null, 2) +
    ";\n",
);
